#!/bin/bash
# Generates src/native/Axon.Native.Trampolines.pas: the fixed pool of callback
# trampolines (see Axon.Native.Callbacks for how they work).
#
#   bash tools/gen_trampolines.sh
#
# SLOTS must match CallbackSlots in Axon.Native.Callbacks.
set -e
SLOTS=32
KINDS=3                       # rtInt, rtFloat64, rtFloat32
TOTAL=$((SLOTS * KINDS))
OUT="$(dirname "$0")/../src/native/Axon.Native.Trampolines.pas"

{
cat <<'EOF'
unit Axon.Native.Trampolines;

(* GENERATED by tools/gen_trampolines.sh -- do not edit by hand.

   The callback trampolines. Slot s (0 <= s < 3 * CallbackSlots) belongs to
   return kind s div CallbackSlots (int, float64, float32).

   Win64: each trampoline saves the integer argument registers into the
   caller's home area (making all arguments one contiguous array of 8-byte
   slots), saves XMM0-3, and calls DispatchWin64. It then loads both RAX and
   XMM0 from the result, so one stub serves every return type.

   macOS: each trampoline is a Pascal function taking 8 integers and 8
   doubles, which receives every register argument of any signature, and
   returns the result in the register its declared type uses. *)

interface

{ The code address of trampoline Slot. }
function TrampolineAddress(Slot: Integer): Pointer;

implementation

uses
  Axon.Native.Callbacks;

{$IFDEF MSWINDOWS}
{$IFDEF CPUX64}
EOF

for ((s = 0; s < TOTAL; s++)); do
cat <<EOF

procedure Tramp$s;
asm
  .NOFRAME
  mov [rsp+8], rcx
  mov [rsp+16], rdx
  mov [rsp+24], r8
  mov [rsp+32], r9
  sub rsp, 88
  movsd qword ptr [rsp+32], xmm0
  movsd qword ptr [rsp+40], xmm1
  movsd qword ptr [rsp+48], xmm2
  movsd qword ptr [rsp+56], xmm3
  mov ecx, $s
  lea rdx, [rsp+96]
  lea r8, [rsp+32]
  lea r9, [rsp+64]
  call DispatchWin64
  mov rax, [rsp+64]
  movsd xmm0, qword ptr [rsp+72]
  add rsp, 88
end;
EOF
done

cat <<'EOF'

{$ENDIF CPUX64}
{$ENDIF MSWINDOWS}

{$IFDEF POSIX}
type
  TRegs = record
    I: array[0..7] of UInt64;
    F: array[0..7] of Double;
  end;
EOF

for ((s = 0; s < TOTAL; s++)); do
  kind=$((s / SLOTS))
  case $kind in
    0) rtype="UInt64"; ret="Result := R.Int;";;
    1) rtype="Double"; ret="Result := PDouble(@R.Float)^;";;
    2) rtype="Single"; ret="Result := PSingle(@R.Float)^;";;
  esac
cat <<EOF

function Tramp$s(x0, x1, x2, x3, x4, x5, x6, x7: UInt64;
  d0, d1, d2, d3, d4, d5, d6, d7: Double): $rtype; cdecl;
var
  G: TRegs;
  R: TCallbackResult;
begin
  G.I[0] := x0; G.I[1] := x1; G.I[2] := x2; G.I[3] := x3;
  G.I[4] := x4; G.I[5] := x5; G.I[6] := x6; G.I[7] := x7;
  G.F[0] := d0; G.F[1] := d1; G.F[2] := d2; G.F[3] := d3;
  G.F[4] := d4; G.F[5] := d5; G.F[6] := d6; G.F[7] := d7;
  DispatchRegs($s, @G.I, @G.F, @R);
  $ret
end;
EOF
done

cat <<'EOF'

{$ENDIF POSIX}

const
  Table: array[0..TRAMPOLINE_LAST] of Pointer = (
EOF
for ((s = 0; s < TOTAL; s++)); do
  sep=","; [ $s -eq $((TOTAL - 1)) ] && sep=""
  echo "    @Tramp$s$sep"
done
cat <<'EOF'
  );

function TrampolineAddress(Slot: Integer): Pointer;
begin
  Result := Table[Slot];
end;

end.
EOF
} | sed "s/TRAMPOLINE_LAST/$((TOTAL - 1))/" > "$OUT"
echo "wrote $OUT ($TOTAL trampolines)"
